import numpy as np

# Create an array
arr = np.array([1, 2, 3, 4, 5])
print("Array:", arr)

# Basic math
print("Sum:", np.sum(arr))
print("Mean:", np.mean(arr))
print("Max:", np.max(arr))

# 2D array (matrix)
matrix = np.array([[1, 2, 3], [4, 5, 6]])
print("\nMatrix:\n", matrix)
print("Shape:", matrix.shape)
